/**
 * 青空文庫のルビ記法を除去する。
 *
 * - `《ふりがな》` 部分を除去
 * - ルビ開始マーカー `｜` も対象パターンと共に除去（ルビと無関係な ｜ は残す）
 * - 親文字（ルビが振られている本文）はそのまま残す
 *
 * @example
 * removeRuby('私は｜彼女《かのじょ》が漢字《かんじ》を書いた')
 * // → '私は彼女が漢字を書いた'
 */
export function removeRuby(text: string): string {
  return text.replace(/｜([^《]*)《[^》]*》/g, '$1').replace(/《[^》]*》/g, '');
}
